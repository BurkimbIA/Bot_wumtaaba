-- Same tables and columns as the SQLite 0.7 schema, so scripts/copy_volume_to_supabase.py copies by name.
-- Timestamps stay epoch seconds and JSON stays text: the store code reads them unchanged.
CREATE TABLE IF NOT EXISTS sessions (
    sender TEXT PRIMARY KEY, state TEXT NOT NULL, updated_at DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS contacts (
    id TEXT PRIMARY KEY, reminders_enabled INTEGER NOT NULL DEFAULT 1,
    created_at DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS conversations (
    id TEXT PRIMARY KEY, contact_id TEXT NOT NULL REFERENCES contacts(id),
    last_inbound_at DOUBLE PRECISION, created_at DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS agreements (
    id TEXT PRIMARY KEY, sender TEXT NOT NULL, data TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL, reference TEXT, client_phone TEXT, contact_id TEXT,
    conversation_id TEXT, client_name TEXT, product TEXT, total BIGINT, paid BIGINT, due_date TEXT);
CREATE INDEX IF NOT EXISTS agreement_owner ON agreements(sender, created_at);
-- seq replaces SQLite's rowid: per-sender order of the queue.
CREATE TABLE IF NOT EXISTS inbox (
    id TEXT PRIMARY KEY, seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    sender TEXT NOT NULL, message TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending',
    attempts INTEGER NOT NULL DEFAULT 0, created_at DOUBLE PRECISION NOT NULL,
    available_at DOUBLE PRECISION NOT NULL, error TEXT);
CREATE TABLE IF NOT EXISTS outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, recipient TEXT NOT NULL,
    content TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending',
    attempts INTEGER NOT NULL DEFAULT 0, created_at DOUBLE PRECISION NOT NULL,
    available_at DOUBLE PRECISION NOT NULL, remote_id TEXT, error TEXT,
    category TEXT NOT NULL DEFAULT 'reply', reminder_id BIGINT);
CREATE UNIQUE INDEX IF NOT EXISTS outbox_reminder ON outbox(reminder_id) WHERE reminder_id IS NOT NULL;
CREATE TABLE IF NOT EXISTS messages (
    id TEXT PRIMARY KEY, conversation_id TEXT NOT NULL REFERENCES conversations(id),
    direction TEXT NOT NULL, type TEXT NOT NULL, text TEXT, payload TEXT NOT NULL,
    source_message_id TEXT, outbox_id BIGINT UNIQUE, remote_id TEXT, status TEXT NOT NULL,
    occurred_at DOUBLE PRECISION NOT NULL);
CREATE INDEX IF NOT EXISTS messages_conversation ON messages(conversation_id, occurred_at);
CREATE TABLE IF NOT EXISTS media_assets (
    message_id TEXT PRIMARY KEY REFERENCES messages(id), media_id TEXT, mime_type TEXT,
    sha256 TEXT, storage_path TEXT, transcript TEXT, metadata TEXT NOT NULL DEFAULT '{}',
    updated_at DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS delivery_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, remote_id TEXT NOT NULL,
    status TEXT NOT NULL, occurred_at DOUBLE PRECISION NOT NULL, payload TEXT NOT NULL,
    UNIQUE(remote_id, status, occurred_at));
CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind TEXT NOT NULL, entity_id TEXT,
    details TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS calendar_events (
    id TEXT PRIMARY KEY, agreement_id TEXT NOT NULL UNIQUE REFERENCES agreements(id),
    owner_sender TEXT NOT NULL, customer_phone TEXT, starts_at DOUBLE PRECISION NOT NULL,
    timezone TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'open');
CREATE TABLE IF NOT EXISTS reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id TEXT NOT NULL REFERENCES calendar_events(id), recipient TEXT NOT NULL,
    role TEXT NOT NULL, scheduled_at DOUBLE PRECISION NOT NULL, status TEXT NOT NULL,
    payload TEXT, outbox_id BIGINT UNIQUE, UNIQUE(event_id, recipient, scheduled_at));
CREATE INDEX IF NOT EXISTS reminders_due ON reminders(status, scheduled_at);
CREATE TABLE IF NOT EXISTS customer_consents (
    agreement_id TEXT NOT NULL REFERENCES agreements(id), phone TEXT NOT NULL,
    granted INTEGER NOT NULL, updated_at DOUBLE PRECISION NOT NULL, source_message_id TEXT,
    PRIMARY KEY(agreement_id, phone));
CREATE TABLE IF NOT EXISTS app_model_config (
    id INTEGER PRIMARY KEY CHECK(id = 1), provider TEXT NOT NULL CHECK(provider IN ('cloud', 'mac')),
    updated_at DOUBLE PRECISION NOT NULL);
